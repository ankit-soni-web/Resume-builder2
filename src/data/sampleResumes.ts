export function createEmptyResume(templateId: TemplateId = 'classic', title = 'Untitled Resume'): Resume {
  const now = new Date().toISOString();
  return {
    id: 'resume-' + Math.random().toString(36).substring(2, 9),
    title,
    createdAt: now,
    updatedAt: now,
    personalInfo: {
      fullName: '',
      jobTitle: '',
      email: '',
      phone: '',
      location: '',
      linkedin: '',
      github: '',
      website: '',
    },
    summary: '',
    experience: [],
    education: [],
    skills: [],
    projects: [],
    certifications: [],
    internships: [],
    awards: [],
    publications: [],
    volunteer: [],
    references: [],
    sectionVisibility: { ...DEFAULT_SECTION_VISIBILITY },
    sectionOrder: [...DEFAULT_SECTION_ORDER],
    design: {
      templateId,
      fontFamily: 'Plus Jakarta Sans',
      fontSize: 'normal',
      lineHeight: 'normal',
      margins: 'normal',
      sectionSpacing: 'normal',
      primaryColor: '#14213D',
      headingStyle: 'left-bar',
      paperSize: 'a4',
      showPhoto: false,
      showPageNumbers: true,
    },
  };
}

